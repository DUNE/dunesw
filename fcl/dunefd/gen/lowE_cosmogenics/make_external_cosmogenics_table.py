#!/usr/bin/env python3
"""
make_external_cosmogenics_table.py
-----------------------------------
Reduce the full external-cosmogenics CSV to the factorised table that
external_cosmogenics_to_hepevt.py samples from.

The CSV is a list of ~190k particles crossing into the detector, but the
generator never reproduces a specific particle: it draws each one Poisson(scale)
times and gives every copy a fresh position and drift-direction sign. The row
list is therefore only ever used as an empirical distribution, and can be
replaced by binned distributions at no cost in what the generator can produce.

Per species this writes:
  * every discrete gamma line at its exact energy (511 keV annihilation,
    1293.6 Ar-41, 1460.9 K-40 and the rest), which binning would otherwise
    smear across a bin,
  * the remaining continuum on quantile-spaced bins, so every bin holds the
    same number of particles and the CDF is exact at each bin edge regardless
    of how many decades the spectrum spans (neutrons cover 11.7),
  * a 2D angular distribution in (cos(theta) about the drift axis, phi).

Energy and direction are binned separately, so their correlation is not kept;
see README.md. Azimuth is binned rather than assumed flat, because it measurably
is not (chi2/ndf = 222 for gammas over 12 bins).

Species with fewer than MIN_HIST entries are written as raw rows instead, since
a histogram of a handful of particles only adds sampling noise.

Usage:
  python make_external_cosmogenics_table.py cosmic_outside_detector.csv \\
      external_cosmogenics_table.dat
"""

import argparse
import csv
import math
import sys

N_E_BINS = 128
N_CT_BINS = 16
N_PHI_BINS = 12
MIN_HIST = 200
MIN_LINE = 50


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input_csv")
    ap.add_argument("output_table")
    args = ap.parse_args()

    by_species = {}
    with open(args.input_csv) as f:
        for row in csv.DictReader(f):
            pdg = int(row["pdgParticle"])
            ekin = float(row["kinEgamma"])
            # CSV x=beam, y=vertical, z=drift; the generator swaps x and z.
            dx, dy, dz = (float(row["dirX"]), float(row["dirY"]), float(row["dirZ"]))
            n = math.sqrt(dx * dx + dy * dy + dz * dz)
            if n == 0.0:
                continue
            by_species.setdefault(pdg, []).append((ekin, dx / n, dy / n, dz / n))

    total = sum(len(v) for v in by_species.values())
    out = open(args.output_table, "w")
    out.write("# external cosmogenics, factorised sampling table\n")
    out.write("# generated by make_external_cosmogenics_table.py from a %d-row CSV\n"
              % total)
    out.write("# energy in keV; cos_theta measured about the drift axis; phi in rad\n")
    out.write("#\n")
    out.write("# SPECIES <pdg> <n_particles> <representation>\n")
    out.write("# L    <ekin_keV> <count>                 discrete line, exact energy\n")
    out.write("# E    <lo_keV> <hi_keV> <count>          quantile-spaced continuum\n")
    out.write("# A    <cos_lo> <cos_hi> <phi_lo> <phi_hi> <count>\n")
    out.write("# RAW  <ekin_keV> <dirX> <dirY> <dirZ>    species below %d particles\n"
              % MIN_HIST)

    for pdg in sorted(by_species, key=lambda p: -len(by_species[p])):
        rows = by_species[pdg]
        if len(rows) < MIN_HIST:
            out.write("\nSPECIES %d %d raw\n" % (pdg, len(rows)))
            for ekin, dx, dy, dz in rows:
                out.write("RAW %.6g %.6f %.6f %.6f\n" % (ekin, dx, dy, dz))
            continue

        out.write("\nSPECIES %d %d binned\n" % (pdg, len(rows)))

        # Split the discrete lines out before binning: they are delta functions
        # and a bin would spread them over its whole width.
        tally = {}
        for r in rows:
            tally[r[0]] = tally.get(r[0], 0) + 1
        lines = {e: c for e, c in tally.items() if c >= MIN_LINE}
        for e in sorted(lines):
            out.write("L %.6g %d\n" % (e, lines[e]))

        # Quantile bins on the continuum: equal occupancy, so bin width follows
        # the spectrum and the CDF is exact at every edge.
        energies = sorted(r[0] for r in rows if r[0] not in lines)
        if energies:
            nb = min(N_E_BINS, len(energies))
            edges = [energies[round(i * (len(energies) - 1) / nb)] for i in range(nb)]
            edges.append(energies[-1])
            for b in range(nb):
                lo, hi = edges[b], edges[b + 1]
                count = (round((b + 1) * len(energies) / nb)
                         - round(b * len(energies) / nb))
                if count and hi > lo:
                    out.write("E %.6g %.6g %d\n" % (lo, hi, count))

        acounts = {}
        for _, dx, dy, dz in rows:
            ct = max(-1.0, min(1.0, dz))
            bi = min(int((ct + 1.0) / 2.0 * N_CT_BINS), N_CT_BINS - 1)
            phi = math.atan2(dy, dx)
            bj = min(int((phi + math.pi) / (2.0 * math.pi) * N_PHI_BINS),
                     N_PHI_BINS - 1)
            acounts[(bi, bj)] = acounts.get((bi, bj), 0) + 1
        for (bi, bj), c in sorted(acounts.items()):
            out.write("A %.4f %.4f %.4f %.4f %d\n"
                      % (-1.0 + 2.0 * bi / N_CT_BINS,
                         -1.0 + 2.0 * (bi + 1) / N_CT_BINS,
                         -math.pi + 2.0 * math.pi * bj / N_PHI_BINS,
                         -math.pi + 2.0 * math.pi * (bj + 1) / N_PHI_BINS, c))

    out.close()
    print("wrote %s from %d particles in %d species"
          % (args.output_table, total, len(by_species)), file=sys.stderr)


if __name__ == "__main__":
    main()
